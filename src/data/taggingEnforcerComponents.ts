const MODES: TaggingComponent['enforcementMode'][] = ['Enforce', 'Audit', 'Remediate', 'Guardrail'];

function resolveDomainAndCloud(idx: number): { domain: EnforcerDomain; cloudScope: CloudTargetScope } {
  if (idx <= 90) {
    return { domain: 'Taxonomy & Schema', cloudScope: 'Multicloud' };
  }
  if (idx <= 180) {
    return { domain: 'AWS Tagging Engine', cloudScope: 'AWS' };
  }
  if (idx <= 270) {
    return { domain: 'Azure Policy & Tagging', cloudScope: 'Azure' };
  }
  if (idx <= 360) {
    return { domain: 'GCP Labels & Resource Tags', cloudScope: 'GCP' };
  }
  if (idx <= 430) {
    return { domain: 'Cross-Cloud Normalization', cloudScope: 'Multicloud' };
  }
  if (idx <= 490) {
    return { domain: 'Drift & Remediation', cloudScope: 'Multicloud' };
  }
  if (idx <= 550) {
    return { domain: 'FinOps & Chargeback', cloudScope: 'Multicloud' };
  }
  if (idx <= 610) {
    return { domain: 'GitOps & Policy-as-Code', cloudScope: 'Multicloud' };
  }
  if (idx <= 660) {
    return { domain: 'Control Plane & UI', cloudScope: 'Multicloud' };
  }
  return { domain: 'Security, GRC & Telemetry', cloudScope: 'Multicloud' };
}

export const TAGGING_ENFORCER_COMPONENTS: TaggingComponent[] = Array.from(
  { length: 700 },
  (_, i) => {
    const num = i + 1;
    const id = `TM-${String(num).padStart(3, '0')}`;
    const baseTitle = RAW_TITLES[i] ?? `Tagging Governance Control #${num}`;
    const { domain, cloudScope } = resolveDomainAndCloud(num);
    const enforcementMode = MODES[i % MODES.length];

    return {
      id,
      index: num,
      title: baseTitle,
      domain,
      cloudScope,
      enforcementMode,
      summary: `${enforcementMode} component in ${domain} (${cloudScope}) for org-wide tagging & labeling governance.`,
    };
  }
);